/// Computes the `RepositoryMapping::entries` for the repos generated by a module extension.
/// While the repos differ in `RepositoryMapping::context_repo`, the entries are identical and
/// sharing the instance ensures that memory and CPU usage are only linear in the number of repos.
// Java: com/google/devtools/build/lib/bazel/bzlmod/ModuleExtensionRepoMappingEntriesFunction.java:41 ModuleExtensionRepoMappingEntriesFunction.compute
pub fn compute(
    key: &ModuleExtensionRepoMappingEntriesKey,
    env: &mut Environment<'_>,
) -> Result<Option<ModuleExtensionRepoMappingEntriesValue>, ComputeError> {
    let Some(bazel_dep_graph_value) = env.get_value(BazelDepGraphKey)? else {
        return Ok(None);
    };

    let module_extension_id = key.argument();
    let Some(extension_eval_value) =
        env.get_value(SingleExtensionValue::key(module_extension_id.clone()))?
    else {
        return Ok(None);
    };

    Ok(Some(compute_repo_mapping_entries(
        module_extension_id,
        &extension_eval_value,
        &bazel_dep_graph_value,
    )))
}

/// Calculates repo mappings for a repo generated from a module extension. Such a repo can see
/// all repos generated by the same module extension, as well as all repos that the Bazel module
/// hosting the extension can see (see above).
// Java: com/google/devtools/build/lib/bazel/bzlmod/ModuleExtensionRepoMappingEntriesFunction.java:63 ModuleExtensionRepoMappingEntriesFunction.computeRepoMappingEntries
fn compute_repo_mapping_entries(
    extension_id: &ModuleExtensionId,
    extension_eval_value: &SingleExtensionValue,
    bazel_dep_graph_value: &BazelDepGraphValue,
) -> ModuleExtensionRepoMappingEntriesValue {
    // Find the key of the module containing this extension. This will be used to compute
    // additional mappings -- any repo generated by an extension contained in the module "foo"
    // can additionally see all repos that "foo" can see.
    let module_key = bazel_dep_graph_value
        .canonical_repo_name_lookup
        .get(extension_id.bzl_file_label().get_repository())
        .unwrap_or_else(|| {
            panic!(
                "NullPointerException: no module for repo {}",
                extension_id.bzl_file_label().get_repository()
            )
        })
        .clone();
    // NOTE(wyv): This means that if "foo" has a bazel_dep with the repo name "bar", and the
    // extension generates an internal repo name "bar", then within a repo generated by the
    // extension, "bar" will refer to the latter. We should explore a way to differentiate between
    // the two to avoid any surprises.
    // LINT.IfChange
    // ImmutableMap.Builder.buildKeepingLast: the last value wins, at the key's first position.
    let mut entries: IndexMap<String, RepositoryName> = IndexMap::new();
    for (k, v) in bazel_dep_graph_value
        .get_full_repo_mapping(&module_key)
        .entries()
    {
        entries.insert(k.clone(), v.clone());
    }
    // canonicalRepoNameToInternalNames().inverse()
    for (canonical, internal) in &extension_eval_value.canonical_repo_name_to_internal_names {
        entries.insert(internal.clone(), canonical.clone());
    }
    if let Some(overrides) = bazel_dep_graph_value.repo_overrides.row(extension_id) {
        for (k, v) in overrides {
            entries.insert(k.clone(), v.clone());
        }
    }
    // LINT.ThenChange(//src/main/java/com/google/devtools/build/lib/bazel/bzlmod/ModuleExtensionEvalStarlarkThreadContext.java)
    ModuleExtensionRepoMappingEntriesValue::create(entries, module_key)
}
