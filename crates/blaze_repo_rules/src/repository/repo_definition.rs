// Java: com/google/devtools/build/lib/skyframe/SkyFunctions.java SkyFunctions.REPO_DEFINITION
pub const REPO_DEFINITION: SkyFunctionName = SkyFunctionName("REPO_DEFINITION");

/// The definition of a repo: the repo rule, its (type-checked) attribute values, its canonical
/// name and, for repos generated by module extensions, the name the extension gave it.
// Java: com/google/devtools/build/lib/bazel/repository/RepoDefinition.java:30 RepoDefinition
#[derive(Debug)]
pub struct RepoDefinition {
    pub repo_rule: Arc<RepoRule>,
    pub attr_values: AttributeValues,
    pub name: String,
    pub original_name: Option<String>,
}

impl RepoDefinition {
    /// `Structure.getValue(field)`: `None` (Java null) for unknown fields.
    // Java: com/google/devtools/build/lib/bazel/repository/RepoDefinition.java:41 RepoDefinition.getValue
    pub fn get_value<'v>(&self, field: &str, heap: Heap<'v>) -> Option<Value<'v>> {
        if field == "name" {
            // Special case: `rctx.attr.name` can be used in place of `rctx.name`.
            return Some(heap.alloc_str(&self.name).to_value());
        }
        if let Some(value) = self.attr_values.get(field) {
            return Some(attribute_value_to_starlark(value, heap));
        }
        let index = *self.repo_rule.attribute_indices.get(field)?;
        let attribute = &self.repo_rule.attributes[index];
        Some(attribute_value_to_starlark(
            &attr_value_to_attribute_value(attribute.get_default_value_unchecked()),
            heap,
        ))
    }

    /// Java `Sets.union(attributeIndices.keySet(), {"name"})`: attribute names in declaration
    /// order, then `name` unless already present.
    // Java: com/google/devtools/build/lib/bazel/repository/RepoDefinition.java:59 RepoDefinition.getFieldNames
    pub fn get_field_names(&self) -> Vec<String> {
        let mut names: Vec<String> = self.repo_rule.attribute_indices.keys().cloned().collect();
        if !names.iter().any(|n| n == "name") {
            names.push("name".to_owned());
        }
        names
    }

    // Java: com/google/devtools/build/lib/bazel/repository/RepoDefinition.java:65 RepoDefinition.getErrorMessageForUnknownField
    pub fn get_error_message_for_unknown_field(&self, field: &str) -> String {
        let names = self.get_field_names();
        format!(
            "unknown attribute {}{}",
            field,
            SpellChecker::did_you_mean(field, names.iter())
        )
    }
}

/// The `rctx.attr` object: a structure over a [`RepoDefinition`] (Java returns the
/// `RepoDefinition` itself, which implements `Structure`).
#[derive(ProvidesStaticType, NoSerialize, Allocative)]
pub struct RepoAttrs(#[allocative(skip)] pub Arc<RepoDefinition>);

starlark_simple_value!(RepoAttrs);

impl fmt::Debug for RepoAttrs {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "RepoAttrs({})", self.0.name)
    }
}

impl fmt::Display for RepoAttrs {
    // PORT: Java's Structure repr is `struct(name = value, ...)` over the attributes; nothing in
    // the corpus prints `rctx.attr`.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "<repository attributes of {}>", self.0.name)
    }
}

#[starlark_value(type = "struct")]
impl<'v> StarlarkValue<'v> for RepoAttrs {
    fn get_attr(&self, attribute: &str, heap: Heap<'v>) -> Option<Value<'v>> {
        self.0.get_value(attribute, heap)
    }

    fn has_attr(&self, attribute: &str, _heap: Heap<'v>) -> bool {
        attribute == "name" || self.0.repo_rule.attribute_indices.contains_key(attribute)
    }

    fn dir_attr(&self) -> Vec<String> {
        self.0.get_field_names()
    }
}

/// The result of looking up a repo definition.
// Java: com/google/devtools/build/lib/bazel/repository/RepoDefinitionValue.java:29 RepoDefinitionValue
#[derive(Debug, Clone)]
pub enum RepoDefinitionValue {
    /// The repo doesn't exist.
    NotFound,
    /// The repo is overridden (`--override_repository`, `@bazel_tools`) to this path.
    RepoOverride(PathFragment),
    /// The repo is defined by a repo rule.
    Found(Arc<RepoDefinition>),
}

impl PartialEq for RepoDefinitionValue {
    fn eq(&self, other: &Self) -> bool {
        match (self, other) {
            (RepoDefinitionValue::NotFound, RepoDefinitionValue::NotFound) => true,
            (RepoDefinitionValue::RepoOverride(a), RepoDefinitionValue::RepoOverride(b)) => a == b,
            (RepoDefinitionValue::Found(a), RepoDefinitionValue::Found(b)) => Arc::ptr_eq(a, b),
            _ => false,
        }
    }
}

/// SkyKey for [`RepoDefinitionValue`]. `Debug` prints `REPO_DEFINITION:@@name`.
// Java: com/google/devtools/build/lib/bazel/repository/RepoDefinitionValue.java:58 RepoDefinitionValue.Key
#[derive(Clone, PartialEq, Eq, Hash)]
pub struct RepoDefinitionKey(pub RepositoryName);

impl RepoDefinitionKey {
    // Java: com/google/devtools/build/lib/bazel/repository/RepoDefinitionValue.java:54 RepoDefinitionValue.key
    pub fn key(repo_name: RepositoryName) -> RepoDefinitionKey {
        RepoDefinitionKey(repo_name)
    }

    pub fn argument(&self) -> &RepositoryName {
        &self.0
    }
}

impl fmt::Debug for RepoDefinitionKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}:{}", REPO_DEFINITION, self.0)
    }
}

impl Key for RepoDefinitionKey {
    type Value = RepoDefinitionValue;
    const FUNCTION: SkyFunctionName = REPO_DEFINITION;
}
