pub struct RepoDefinitionKey(pub RepositoryName);

impl RepoDefinitionKey {
    // Java: com/google/devtools/build/lib/bazel/repository/RepoDefinitionValue.java:54 RepoDefinitionValue.key
    pub fn key(repo_name: RepositoryName) -> RepoDefinitionKey {
        RepoDefinitionKey(repo_name)
    }

    pub fn argument(&self) -> &RepositoryName {
        &self.0
    }
}

impl fmt::Debug for RepoDefinitionKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}:{}", REPO_DEFINITION, self.0)
    }
}

