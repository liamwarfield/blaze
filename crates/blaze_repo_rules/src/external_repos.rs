//! The real [`ExternalRepos`] implementation: repository mappings from Bzlmod and repository
//! directories from repository rules.
//!
//! `blaze_sky_loading::repos` owns the REPOSITORY_MAPPING and REPOSITORY_DIRECTORY functions and
//! delegates their Bzlmod-specific parts to an `ExternalRepos`:
//! - [`BzlmodExternalRepos::compute_repository_mapping`] is the rest of Java
//!   `RepositoryMappingFunction.computeInternal` (module repos, extension repos, not found);
//! - [`BzlmodExternalRepos::compute_repository_directory`] is Java
//!   `RepositoryFetchFunction.compute`.

use std::sync::Arc;

use blaze_bzlmod::skyframe::keys::BazelDepGraphKey;
use blaze_bzlmod_model::BazelDepGraphValue;
use blaze_bzlmod_model::ModuleExtensionId;
use blaze_cmdline::RepositoryMapping;
use blaze_cmdline::RepositoryName;
use blaze_sky_loading::repos::ExternalRepos;
use blaze_sky_loading::repos::RepositoryDirectoryValue;
use blaze_sky_loading::repos::RepositoryMappingValue;
use blaze_skyframe::ComputeError;
use blaze_skyframe::Environment;

use crate::bzlmod::repo_mapping_entries::ModuleExtensionRepoMappingEntriesKey;
use crate::repository::repository_fetch_function::RepositoryFetchFunction;

/// [`ExternalRepos`] backed by Bzlmod resolution, module extensions and repository rules.
pub struct BzlmodExternalRepos {
    fetch_function: Arc<RepositoryFetchFunction>,
}

impl BzlmodExternalRepos {
    pub fn new(fetch_function: Arc<RepositoryFetchFunction>) -> Self {
        BzlmodExternalRepos { fetch_function }
    }

    /// Calculates repo mappings for a repo generated from a Bazel module. Such a repo can see all
    /// its `bazel_dep`s, as well as any repos generated by an extension it has a `use_repo`
    /// clause for.
    // Java: com/google/devtools/build/lib/skyframe/RepositoryMappingFunction.java:128 RepositoryMappingFunction.computeForBazelModuleRepo
    fn compute_for_bazel_module_repo(
        repository_name: &RepositoryName,
        bazel_dep_graph_value: &BazelDepGraphValue,
    ) -> Option<RepositoryMappingValue> {
        let module_key = bazel_dep_graph_value
            .canonical_repo_name_lookup
            .get(repository_name)?;
        let module = bazel_dep_graph_value
            .dep_graph
            .get(module_key)
            .expect("the dep graph has every module of the lookup");
        Some(RepositoryMappingValue::create(
            bazel_dep_graph_value.get_full_repo_mapping(module_key),
            module.name.clone(),
            module.version.get_normalized(),
        ))
    }

    // Java: com/google/devtools/build/lib/skyframe/RepositoryMappingFunction.java:143 RepositoryMappingFunction.maybeGetModuleExtensionForRepo
    fn maybe_get_module_extension_for_repo(
        repository_name: &RepositoryName,
        bazel_dep_graph_value: &BazelDepGraphValue,
    ) -> Option<ModuleExtensionId> {
        bazel_dep_graph_value
            .extension_unique_names
            .iter()
            .find(|(_, unique_name)| {
                repository_name
                    .get_name()
                    .starts_with(&format!("{unique_name}+"))
            })
            .map(|(id, _)| id.clone())
    }
}

impl ExternalRepos for BzlmodExternalRepos {
    // Java: com/google/devtools/build/lib/skyframe/RepositoryMappingFunction.java:73 RepositoryMappingFunction.computeInternal
    fn compute_repository_mapping(
        &self,
        repository_name: &RepositoryName,
        env: &mut Environment<'_>,
    ) -> Result<Option<RepositoryMappingValue>, ComputeError> {
        let Some(bazel_dep_graph_value) = env.get_value(BazelDepGraphKey)? else {
            return Ok(None);
        };

        // Try and see if this is a repo generated from a Bazel module.
        if let Some(mapping_value) =
            Self::compute_for_bazel_module_repo(repository_name, &bazel_dep_graph_value)
        {
            return Ok(Some(if repository_name.is_main() {
                mapping_value.with_cached_inverse_map()
            } else {
                mapping_value
            }));
        }

        // Now try and see if this is a repo generated from a module extension.
        if let Some(module_extension_id) =
            Self::maybe_get_module_extension_for_repo(repository_name, &bazel_dep_graph_value)
        {
            let Some(repo_mapping_entries_value) = env.get_value(
                ModuleExtensionRepoMappingEntriesKey::key(module_extension_id),
            )?
            else {
                return Ok(None);
            };
            return Ok(Some(RepositoryMappingValue::create(
                // Avoids repeated computation of the hash code for the same entries object.
                RepositoryMapping::create(
                    repo_mapping_entries_value.entries.clone(),
                    repository_name.clone(),
                ),
                repo_mapping_entries_value.module_key.name(),
                repo_mapping_entries_value
                    .module_key
                    .version()
                    .get_normalized(),
            )));
        }

        Ok(Some(RepositoryMappingValue::not_found_value()))
    }

    // Java: com/google/devtools/build/lib/bazel/repository/RepositoryFetchFunction.java:140 RepositoryFetchFunction.compute
    fn compute_repository_directory(
        &self,
        repository_name: &RepositoryName,
        env: &mut Environment<'_>,
    ) -> Result<Option<RepositoryDirectoryValue>, ComputeError> {
        self.fetch_function.compute(repository_name, env)
    }
}
