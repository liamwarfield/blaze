/// The parts of the compile `Action` that header discovery reads.
pub trait DiscoveringAction {
    /// Java: `action.getOwner().getLabel().toString()`.
    fn get_owner_label(&self) -> String;
    /// Java: `action.getOwner().getLabel().getRepository().getName()`.
    fn get_owner_repository_name(&self) -> String;
    /// Java: `getOsFromConstraintsOrHost(action.getExecutionPlatform())`.
    fn get_execution_os(&self) -> OS;
    /// Java: `action.getInputs()`.
    fn get_inputs(&self) -> NestedSet<ArtifactRef>;
}

/// Returns a collection with additional input artifacts relevant to the action by reading the
/// dynamically-discovered dependency information from the parsed dependency set after the action
/// has run.
///
/// Artifacts are considered inputs but not "mandatory" inputs.
///
/// Fails iff the .d is missing (when required), malformed, or has unresolvable included
/// artifacts.
// Java: com/google/devtools/build/lib/rules/cpp/HeaderDiscovery.java:68 HeaderDiscovery.discoverInputsFromDependencies
pub fn discover_inputs_from_dependencies(
    action: &dyn DiscoveringAction,
    source_file: &ArtifactRef,
    should_validate_inclusions: bool,
    dependencies: &[Path],
    permitted_system_include_prefixes: &[Path],
    allowed_derived_inputs: &NestedSet<ArtifactRef>,
    exec_root: &Path,
    artifact_resolver: &dyn ArtifactResolver,
    sibling_repository_layout: bool,
    path_mapper: &dyn PathMapper,
) -> Result<NestedSet<ArtifactRef>, ActionExecutionException> {
    let mut regular_derived_artifacts: HashMap<PathFragment, ArtifactRef> = HashMap::new();
    // PORT: java-hash-order. Java uses a HashMap; its order is only observable through
    // findOwningTreeArtifact's findAny when tree artifacts nest. Insertion order is used.
    let mut tree_artifacts: IndexMap<PathFragment, ArtifactRef> = IndexMap::new();
    for a in allowed_derived_inputs.to_list().iter() {
        if a.is_source_artifact() {
            continue;
        }
        // We may encounter duplicate keys in the derived inputs if two artifacts have different
        // owners. Just use the first one. The two artifacts must be generated by equivalent
        // (shareable) actions in order to have not generated a conflict in Bazel.
        if a.is_tree_artifact() {
            tree_artifacts
                .entry(path_mapper.map(&a.get_exec_path()))
                .or_insert_with(|| a.clone());
        } else {
            regular_derived_artifacts
                .entry(path_mapper.map(&a.get_exec_path()))
                .or_insert_with(|| a.clone());
        }
    }

    run_discovery(
        action,
        source_file,
        should_validate_inclusions,
        dependencies,
        permitted_system_include_prefixes,
        &regular_derived_artifacts,
        &tree_artifacts,
        exec_root,
        artifact_resolver,
        sibling_repository_layout,
        path_mapper,
    )
}

// Java: com/google/devtools/build/lib/vfs/FileSystemUtils.java:896 FileSystemUtils.startsWithAny
fn starts_with_any(path: &Path, prefixes: &[Path]) -> bool {
    prefixes.iter().any(|prefix| path.starts_with(prefix))
}

// Java: com/google/devtools/build/lib/vfs/FileSystemUtils.java:909 FileSystemUtils.startsWithAnyIgnoringCase
fn starts_with_any_ignoring_case(path: &Path, prefixes: &[Path]) -> bool {
    prefixes
        .iter()
        .any(|prefix| path.starts_with_ignoring_case(prefix))
}

// Java: com/google/devtools/build/lib/rules/cpp/HeaderDiscovery.java:118 HeaderDiscovery.runDiscovery
fn run_discovery(
    action: &dyn DiscoveringAction,
    source_file: &ArtifactRef,
    should_validate_inclusions: bool,
    dependencies: &[Path],
    permitted_system_include_prefixes: &[Path],
    regular_derived_artifacts: &HashMap<PathFragment, ArtifactRef>,
    tree_artifacts: &IndexMap<PathFragment, ArtifactRef>,
    exec_root: &Path,
    artifact_resolver: &dyn ArtifactResolver,
    sibling_repository_layout: bool,
    path_mapper: &dyn PathMapper,
) -> Result<NestedSet<ArtifactRef>, ActionExecutionException> {
    let mut inputs: NestedSetBuilder<ArtifactRef> = NestedSetBuilder::stable_order();

    // This is a very special case: in certain corner cases (notably, protobuf), the WORKSPACE
    // file contains a local_repository that has the same name and path as the main repository.
    // In this case, if sibling repository layout is active, files in that local repository have
    // the same absolute execpath as files in the main repository but not the same *relative*
    // execpath (e.g. a:b would be ../repo/a/b in the local_repository and a/b in the main
    // repository). The flag hacks around this by pretending that such artifacts are always in the
    // local_repository if the action is in it.
    let ignore_main_repository = sibling_repository_layout
        && action.get_owner_repository_name() == exec_root.get_base_name();

    // Check inclusions.
    let mut absolute_path_problems = IncludeProblems::new();
    let mut unresolvable_path_problems = IncludeProblems::new();
    let possibly_case_insensitive_file_system = action.get_execution_os() == OS::WINDOWS;
    let mut source_artifact_inputs: Option<HashSet<ArtifactRef>> = None;
    for exec_path in dependencies {
        let mut exec_path_fragment = exec_path.as_fragment().clone();
        if exec_path_fragment.is_absolute() {
            if possibly_case_insensitive_file_system {
                // Absolute includes from system paths are ignored. With a case-insensitive file
                // system, the paths as reported by the compiler may differ in casing from those
                // listed by the toolchain.
                if starts_with_any_ignoring_case(exec_path, permitted_system_include_prefixes) {
                    continue;
                }
            } else if starts_with_any(exec_path, permitted_system_include_prefixes) {
                continue;
            }
            let exec_root_parent = exec_root.get_parent_directory();
            if exec_path.starts_with(exec_root)
                && (!ignore_main_repository
                    || artifact_resolver.is_derived_artifact(&exec_path.relative_to(exec_root)))
            {
                exec_path_fragment = exec_path.relative_to(exec_root); // funky but tolerable path
            } else if sibling_repository_layout
                && exec_root_parent
                    .as_ref()
                    .is_some_and(|parent| exec_path.starts_with(parent))
            {
                // for --experimental_sibling_repository_layout
                exec_path_fragment = EXPERIMENTAL_EXTERNAL_PATH_PREFIX
                    .get_relative(&exec_path.relative_to(exec_root_parent.as_ref().unwrap()));
            } else {
                // Since gcc is given only relative paths on the command line, non-builtin include
                // paths here should never be absolute. If they are, it's probably due to a
                // non-hermetic #include, and we should stop the build with an error.
                absolute_path_problems.add(exec_path_fragment.get_path_string());
                continue;
            }
        }
        let mut resolved_artifacts: Vec<ArtifactRef> = Vec::new();
        match regular_derived_artifacts.get(&exec_path_fragment) {
            None => {
                let pkg_id = PackageIdentifier::discover_from_exec_path(
                    &exec_path_fragment,
                    false,
                    sibling_repository_layout,
                );
                if let Some(pkg_id) = pkg_id {
                    if possibly_case_insensitive_file_system {
                        resolved_artifacts = artifact_resolver
                            .resolve_source_artifacts_ascii_case_insensitively(
                                &exec_path_fragment,
                                pkg_id.get_repository(),
                            );
                    } else if let Some(source_artifact) = artifact_resolver
                        .resolve_source_artifact(&exec_path_fragment, pkg_id.get_repository())
                    {
                        resolved_artifacts = vec![source_artifact];
                    }
                }
            }
            Some(derived_artifact) => {
                resolved_artifacts = vec![derived_artifact.clone()];
            }
        }
        if !resolved_artifacts.is_empty() {
            // We don't need to add the sourceFile itself as it is a mandatory input.
            let resolved_artifacts: Vec<ArtifactRef> = resolved_artifacts
                .into_iter()
                .filter(|a| a != source_file)
                .collect();
            match resolved_artifacts.len() {
                0 => {}
                1 => {
                    inputs.add(resolved_artifacts[0].clone());
                }
                _ => {
                    let source_artifact_inputs = source_artifact_inputs.get_or_insert_with(|| {
                        action
                            .get_inputs()
                            .to_list()
                            .iter()
                            .filter(|input| input.is_source_artifact())
                            .cloned()
                            .collect()
                    });
                    if !resolved_artifacts
                        .iter()
                        .any(|a| source_artifact_inputs.contains(a))
                    {
                        inputs.add_all(resolved_artifacts);
                    } else {
                        for resolved_artifact in resolved_artifacts {
                            if source_artifact_inputs.contains(&resolved_artifact) {
                                inputs.add(resolved_artifact);
                            }
                        }
                    }
                }
            }
            continue;
        } else if exec_path_fragment.get_file_extension() == "cppmap" {
            // Transitive cppmap files are added to the dotd files of compiles even though they are
            // not required for compilation. Since they're not explicit inputs to the action this
            // only happens when sandboxing is disabled.
            continue;
        }

        let tree_artifact =
            find_owning_tree_artifact(&exec_path_fragment, tree_artifacts, path_mapper);
        if let Some(tree_artifact) = tree_artifact {
            inputs.add(tree_artifact);
        } else {
            // Record a problem if we see files that we can't resolve, likely caused by undeclared
            // includes or illegal include constructs.
            unresolvable_path_problems.add(exec_path_fragment.get_path_string());
        }
    }
    if should_validate_inclusions {
        absolute_path_problems.assert_problem_free(&format!(
            "absolute path inclusion(s) found in rule '{}':\nthe source file '{}' includes the \
             following non-builtin files with absolute paths (if these are builtin files, make \
             sure these paths are in your toolchain):",
            action.get_owner_label(),
            source_file.pretty_print()
        ))?;
        unresolvable_path_problems.assert_problem_free(&format!(
            "undeclared inclusion(s) in rule '{}':\nthis rule is missing dependency declarations \
             for the following files included by '{}':",
            action.get_owner_label(),
            source_file.pretty_print()
        ))?;
    }
    Ok(inputs.build())
}

// Java: com/google/devtools/build/lib/rules/cpp/HeaderDiscovery.java:288 HeaderDiscovery.findOwningTreeArtifact
fn find_owning_tree_artifact(
    exec_path: &PathFragment,
    tree_artifacts: &IndexMap<PathFragment, ArtifactRef>,
    path_mapper: &dyn PathMapper,
) -> Option<ArtifactRef> {
    // Check the map for the exec path's parent directory first. If the exec path matches a direct
    // child of a tree artifact (a common case), we can skip the full iteration below.
    let dir = exec_path
        .get_parent_directory()
        .unwrap_or_else(|| panic!("NullPointerException"));
    if let Some(tree) = tree_artifacts.get(&dir) {
        return Some(tree.clone());
    }

    // Search for any tree artifact that encloses the exec path.
    tree_artifacts
        .values()
        .find(|a| dir.starts_with(&path_mapper.map(&a.get_exec_path())))
        .cloned()
}
