/// A SkyValue that wraps a [`RepositoryMapping`].
///
/// - `repository_mapping`: the actual repo mapping; `None` if the requested repo doesn't exist.
/// - `associated_module_name`: the name of the Bzlmod module associated with the requested repo.
///   For repos generated by module extensions, this is the name of the module hosting the
///   extension.
/// - `associated_module_version`: the (normalized) version of that module.
