    pub fn associated_module_name(&self) -> Option<&str> {
        self.associated_module_name.as_deref()
    }

    // Java: com/google/devtools/build/lib/skyframe/RepositoryMappingValue.java:47 RepositoryMappingValue.associatedModuleVersion
    pub fn associated_module_version(&self) -> Option<&str> {
        self.associated_module_version.as_deref()
    }

    /// Replaces the inner repository mapping with one returned by calling its
    /// `with_additional_mappings` method. Panics (Java NPE) on the not-found value.
