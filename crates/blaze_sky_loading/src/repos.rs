/// One repository as recorded by `scripts/w3/oracle-repos`.
#[derive(Clone, Debug)]
struct OracleRepo {
    found: bool,
    mapping: Option<Vec<(String, String)>>,
    module_name: Option<String>,
    module_version: Option<String>,
    directory: Option<String>,
}

/// [`ExternalRepos`] from the oracle: repository mappings recorded with `bazel mod
/// dump_repo_mapping`, and repository directories fetched by the oracle, read from
/// `~/.cache/blaze/w3/<project>.repos.json` (written by `scripts/w3/oracle-repos`; the format is
/// documented there).
///
/// REPOSITORY_DIRECTORY treats the recorded directory like a repository override: it makes
/// `<output_base>/external/<name>` a symlink to it (Java `RepositoryFetchFunction.symlinkRepoRoot`,
/// the same code path Bazel takes for a repo found in the repo contents cache) and returns that
/// path as the root, so paths Blaze prints are `<output_base>/external/<name>/...` as Bazel's are.
///
/// PORT: W3 only. Differences from real Bazel, all loud:
/// - a repository the oracle knows but never fetched (no directory, e.g. re2's `@@libpfm+`) fails
///   with an [`IOException`] naming the repo instead of running its repository rule;
/// - a canonical name absent from the recording is NOT_FOUND (the recording is closed under every
///   canonical name any recorded mapping names, plus every repo the oracle fetched).
pub struct OracleRepos {
    repos: HashMap<String, OracleRepo>,
    directories: LoadingDirectories,
}

/// An error reading the repos JSON.
#[derive(Debug, thiserror::Error)]
#[error("{0}")]
pub struct OracleReposError(pub String);

/// The internal string of a Unicode string of the repos JSON.
fn internal(s: &str) -> String {
    blaze_util::string_encoding::unicode_to_internal(s).into_owned()
}

impl OracleRepos {
    /// Reads the JSON written by `scripts/w3/oracle-repos`.
    pub fn load(
        json_path: &std::path::Path,
        directories: LoadingDirectories,
    ) -> Result<OracleRepos, OracleReposError> {
        let shown = blaze_util::string_encoding::platform_to_internal(json_path.as_os_str());
        // The file is JSON text (UTF-8, as Python's json module writes it).
        let text = std::fs::read(json_path)
            .and_then(|bytes| String::from_utf8(bytes).map_err(std::io::Error::other))
            .map_err(|e| OracleReposError(format!("{}: {}", shown, e)))?;
        Self::parse(&text, directories).map_err(|e| OracleReposError(format!("{}: {}", shown, e.0)))
    }

    /// Parses the JSON written by `scripts/w3/oracle-repos`. Its strings are Unicode; the names
    /// and paths Blaze keeps are their internal strings.
    pub fn parse(
        text: &str,
        directories: LoadingDirectories,
    ) -> Result<OracleRepos, OracleReposError> {
        let err = |m: &str| OracleReposError(m.to_owned());
        let json: serde_json::Value =
            serde_json::from_str(text).map_err(|e| OracleReposError(e.to_string()))?;
        if json.get("format").and_then(|f| f.as_i64()) != Some(1) {
            return Err(err("unsupported repos.json format (want 1)"));
        }
        let repos_json = json
            .get("repos")
            .and_then(|r| r.as_object())
            .ok_or_else(|| err("missing \"repos\" object"))?;
        let mut repos = HashMap::new();
        for (name, r) in repos_json {
            let found = r
                .get("found")
                .and_then(|f| f.as_bool())
                .ok_or_else(|| OracleReposError(format!("repo {:?}: missing \"found\"", name)))?;
            let mapping = match r.get("mapping") {
                None | Some(serde_json::Value::Null) => None,
                Some(serde_json::Value::Array(entries)) => {
                    let mut out = Vec::with_capacity(entries.len());
                    for e in entries {
                        let pair = e.as_array().filter(|a| a.len() == 2).ok_or_else(|| {
                            OracleReposError(format!("repo {:?}: bad mapping entry {}", name, e))
                        })?;
                        let (Some(k), Some(v)) = (pair[0].as_str(), pair[1].as_str()) else {
                            return Err(OracleReposError(format!(
                                "repo {:?}: bad mapping entry {}",
                                name, e
                            )));
                        };
                        out.push((internal(k), internal(v)));
                    }
                    Some(out)
                }
                Some(other) => {
                    return Err(OracleReposError(format!(
                        "repo {:?}: bad mapping {}",
                        name, other
                    )));
                }
            };
            let string_field = |field: &str| r.get(field).and_then(|v| v.as_str()).map(internal);
            repos.insert(
                internal(name),
                OracleRepo {
                    found,
                    mapping,
                    module_name: string_field("module_name"),
                    module_version: string_field("module_version"),
                    directory: string_field("directory"),
                },
            );
        }
        Ok(OracleRepos { repos, directories })
    }

    fn file_system(&self) -> &FileSystemRef {
        self.directories.get_output_base().get_file_system()
    }
}

impl ExternalRepos for OracleRepos {
    fn compute_repository_mapping(
        &self,
        repository_name: &RepositoryName,
        _env: &mut Environment<'_>,
    ) -> Result<Option<RepositoryMappingValue>, ComputeError> {
        // PORT: Java finds non-visible names neither in the canonical repo name lookup (their
        // equality includes the context repo) nor, in practice, by extension prefix.
        if !repository_name.is_visible() {
            return Ok(Some(RepositoryMappingValue::not_found_value()));
        }
        let Some(repo) = self.repos.get(repository_name.get_name()) else {
            return Ok(Some(RepositoryMappingValue::not_found_value()));
        };
        if !repo.found {
            return Ok(Some(RepositoryMappingValue::not_found_value()));
        }
        let entries = repo
            .mapping
            .as_ref()
            .expect("a found repo has a mapping")
            .iter()
            .map(|(apparent, canonical)| {
                (
                    apparent.clone(),
                    RepositoryName::create_unvalidated(canonical),
                )
            });
        let mapping = RepositoryMapping::create(entries, repository_name.clone());
        let value = match (&repo.module_name, &repo.module_version) {
            (Some(name), Some(version)) => {
                RepositoryMappingValue::create(mapping, name.clone(), version.clone())
            }
            _ => RepositoryMappingValue::create_special(Some(mapping)),
        };
        // Java: the main repo's mapping caches its inverse (computeInternal).
        Ok(Some(if repository_name.is_main() {
            value.with_cached_inverse_map()
        } else {
            value
        }))
    }

    // Java: com/google/devtools/build/lib/bazel/repository/RepositoryFetchFunction.java:140 RepositoryFetchFunction.compute
    fn compute_repository_directory(
        &self,
        repository_name: &RepositoryName,
        env: &mut Environment<'_>,
    ) -> Result<Option<RepositoryDirectoryValue>, ComputeError> {
        if STARLARK_SEMANTICS.get(env)?.is_none() {
            return Ok(None);
        }
        if !repository_name.is_visible() {
            return Ok(Some(RepositoryDirectoryValue::Failure {
                error_msg: format!(
                    "No repository visible as '@{}' from {}",
                    repository_name.get_name(),
                    repository_name.get_context_repo_display_string()
                ),
            }));
        }
        if repository_name.is_main() {
            blaze_util::unported!("RepositoryFetchFunction.compute for the main repository");
        }
        let repo_root = self
            .directories
            .get_external_repository_directory()
            .get_relative_str(repository_name.get_name());
        let repo = self
            .repos
            .get(repository_name.get_name())
            .filter(|r| r.found);
        let Some(repo) = repo else {
            return Ok(Some(RepositoryDirectoryValue::Failure {
                error_msg: format!("Repository '{}' is not defined", repository_name),
            }));
        };
        let Some(directory) = &repo.directory else {
            return Err(SkyFunctionException::persistent(IOException::new(format!(
                "OracleRepos: repository '{}' is defined but was never fetched by the oracle \
                 (no directory under the oracle's output base); Blaze cannot fetch repositories \
                 yet",
                repository_name
            )))
            .into());
        };
        let destination = Path::create_from_str(directory, self.file_system());
        symlink_repo_root(
            &self.directories,
            &repo_root,
            &destination,
            repository_name.get_name(),
            env,
        )
    }
}

