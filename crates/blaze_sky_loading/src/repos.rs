// The seam

/// Supplies what Bzlmod and repository fetching compute: repository mappings and repository
/// directories. Implementations request their own Skyframe dependencies through `env` and keep
/// Java's protocol (`Ok(None)` when a dependency is missing).
///
/// - [`ExternalRepos::compute_repository_mapping`] is the part of Java
///   `RepositoryMappingFunction.computeInternal` after the `@_builtins` branch (module repos from
///   `BazelDepGraphValue`, extension repos from `ModuleExtensionRepoMappingEntriesValue`, else
///   `NOT_FOUND_VALUE`). The REPOSITORY_MAPPING function itself handles STARLARK_SEMANTICS,
///   `@_builtins`, and the `--override_repository` check of `compute`.
/// - [`ExternalRepos::compute_repository_directory`] is Java `RepositoryFetchFunction.compute`
///   (REPOSITORY_DIRECTORY): `Success` with `<output_base>/external/<name>` as root, or `Failure`;
///   fetch errors are thrown (Java `RepositoryFunctionException`, wrapping an `IOException` here
///   as [`IOException`]).
pub trait ExternalRepos: Send + Sync + 'static {
    fn compute_repository_mapping(
        &self,
        repository_name: &RepositoryName,
        env: &mut Environment<'_>,
    ) -> Result<Option<RepositoryMappingValue>, ComputeError>;

    fn compute_repository_directory(
        &self,
        repository_name: &RepositoryName,
        env: &mut Environment<'_>,
    ) -> Result<Option<RepositoryDirectoryValue>, ComputeError>;

    /// Java `(BazelDepGraphValue) env.getValue(BazelDepGraphValue.KEY)`, for loading code that
    /// reads the dependency graph itself (`AutoloadSymbols.getLoadKeys`).
    fn get_bazel_dep_graph_value(
        &self,
        _env: &mut Environment<'_>,
    ) -> Result<Option<Arc<blaze_bzlmod_model::BazelDepGraphValue>>, ComputeError> {
        blaze_util::unported!("ExternalRepos.get_bazel_dep_graph_value (BazelDepGraphValue.KEY)")
    }

    /// Java `((ModuleFileValue) env.getValue(ModuleFileValue.KEY_FOR_ROOT_MODULE)).module()
    /// .getName()` (StarlarkBuiltinsFunction with autoloads).
    fn get_root_module_name(
        &self,
        _env: &mut Environment<'_>,
    ) -> Result<Option<String>, ComputeError> {
        blaze_util::unported!(
            "ExternalRepos.get_root_module_name (ModuleFileValue.KEY_FOR_ROOT_MODULE)"
        )
    }
}

/// Java `StarlarkBuiltinsValue.isBuiltinsRepo`.
// Java: com/google/devtools/build/lib/skyframe/StarlarkBuiltinsValue.java:37 StarlarkBuiltinsValue.isBuiltinsRepo
pub fn is_builtins_repo(repo: &RepositoryName) -> bool {
    // Use String.equals(), not RepositoryName.equals(), to force case sensitivity.
    repo.get_name() == BUILTINS.get_name() && repo.is_visible()
}

/// SkyFunction for [`RepositoryMappingValue`]s.
// Java: com/google/devtools/build/lib/skyframe/RepositoryMappingFunction.java:40 RepositoryMappingFunction
pub struct RepositoryMappingFunction {
    /// Java `ruleClassProvider.getToolsRepository()`.
    tools_repository: Option<RepositoryName>,
    external_repos: Arc<dyn ExternalRepos>,
}

impl RepositoryMappingFunction {
    // Java: com/google/devtools/build/lib/skyframe/RepositoryMappingFunction.java:43 RepositoryMappingFunction.<init>
    pub fn new(
        tools_repository: Option<RepositoryName>,
        external_repos: Arc<dyn ExternalRepos>,
    ) -> Self {
        RepositoryMappingFunction {
            tools_repository,
            external_repos,
        }
    }

    // PORT: skipped, errors are `SkyFunctionException::persistent/transient` around the cause: RepositoryMappingFunction.RepositoryMappingFunctionException.<init>
    // Java: com/google/devtools/build/lib/skyframe/RepositoryMappingFunction.java:49 RepositoryMappingFunction.compute
    pub fn compute(
        &self,
        key: &RepositoryMappingKey,
        env: &mut Environment<'_>,
    ) -> Result<Option<RepositoryMappingValue>, ComputeError> {
        let Some(repository_mapping_value) = self.compute_internal(key, env)? else {
            return Ok(None);
        };
        if repository_mapping_value.is_not_found() {
            let Some(overrides) = REPOSITORY_OVERRIDES.get(env)? else {
                return Ok(None);
            };
            if overrides.contains_key(key.repo_name().get_name()) {
                // Use this rather than NoSuchThingException so that the error mentions the
                // requested target.
                return Err(SkyFunctionException::persistent(NoSuchPackageException::new(
                    PackageIdentifier::create(key.repo_name().clone(), PathFragment::empty_fragment()),
                    format!(
                        "the repository {} does not exist, but has been specified as overridden \
                         with --override_repository. Use --inject_repository instead to add a new \
                         repository.",
                        key.repo_name()
                    ),
                ))
                .into());
            }
        }
        Ok(Some(repository_mapping_value))
    }

    // Java: com/google/devtools/build/lib/skyframe/RepositoryMappingFunction.java:73 RepositoryMappingFunction.computeInternal
    fn compute_internal(
        &self,
        sky_key: &RepositoryMappingKey,
        env: &mut Environment<'_>,
    ) -> Result<Option<RepositoryMappingValue>, ComputeError> {
        if STARLARK_SEMANTICS.get(env)?.is_none() {
            return Ok(None);
        }
        let repository_name = sky_key.repo_name();

        if is_builtins_repo(repository_name) {
            // If tools repo is not set, use the default empty mapping.
            let Some(tools_repository) = &self.tools_repository else {
                return Ok(Some(
                    RepositoryMappingValue::default_value_for_builtins_repo(),
                ));
            };
            // Builtins .bzl files should use the repo mapping of @bazel_tools, to get access to
            // repos such as @platforms.
            let Some(bazel_tools_mapping) =
                env.get_value(RepositoryMappingKey::key(tools_repository.clone()))?
            else {
                return Ok(None);
            };
            return Ok(Some(
                RepositoryMappingValue::default_value_for_builtins_repo()
                    .with_additional_mappings(bazel_tools_mapping.repository_mapping()),
            ));
        }

        // PORT: the rest (module repos, extension repos, NOT_FOUND_VALUE) needs Bzlmod; it is the
        // ExternalRepos implementation's.
        self.external_repos
            .compute_repository_mapping(repository_name, env)
    }
}

