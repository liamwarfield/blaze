    // Java: com/google/devtools/build/lib/actions/Artifact.java:237 DerivedArtifact.<init>
    fn new_derived(
        root: ArtifactRoot,
        exec_path: PathFragment,
        owner_key: ActionLookupKeyRef,
        generating_action_key: Option<ActionLookupData>,
        class: DerivedClass,
    ) -> Artifact {
        check_state!(
            !root.get_exec_path().is_empty(),
            "Derived root has no exec path: {}, {}",
            root,
            exec_path
        );
        let lock = OnceLock::new();
        if let Some(k) = generating_action_key {
            let _ = lock.set(k);
        }
        Artifact(Arc::new(ArtifactInner {
            root,
            exec_path,
            kind: ArtifactKind::Derived(DerivedData {
                owner_key,
                generating_action_key: lock,
                class,
            }),
        }))
    }

    /// Creates a `TreeFileArtifact` under a shared tree artifact.
    ///
    /// The `parent` must be a tree artifact owned by an action (not an action template
    /// expansion). The returned child is owned by the parent's generating action.
    // Java: com/google/devtools/build/lib/actions/Artifact.java:1067 TreeFileArtifact.createTreeOutput
    pub fn create_tree_output(parent: &Artifact, parent_relative_path: PathFragment) -> Artifact {
        check_argument!(
            parent.has_generating_action_key(),
            "{} has no generating action key (parent owner: {}, parent relative path: {})",
            parent,
            parent.get_artifact_owner(),
            parent_relative_path
        );
        let generating_action_key = parent.get_generating_action_key().clone();
        check_argument!(
            !is_action_template_expansion_key(generating_action_key.get_action_lookup_key()),
            "{} owned by action template expansion {} (parent relative path: {})",
            parent,
            generating_action_key.get_action_lookup_key(),
            parent_relative_path
        );
        let owner_key = generating_action_key.get_action_lookup_key().clone();
        Artifact::new_tree_file(
            parent,
            parent_relative_path,
            owner_key,
            Some(generating_action_key),
        )
    }

