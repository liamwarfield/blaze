    /// The Java class of this artifact.
    pub fn artifact_class(&self) -> ArtifactClass {
        match &self.0.kind {
            ArtifactKind::Source { .. } => ArtifactClass::SourceArtifact,
            ArtifactKind::Derived(d) => match d.class {
                DerivedClass::Derived => ArtifactClass::DerivedArtifact,
                DerivedClass::Special(_) => ArtifactClass::SpecialArtifact,
                DerivedClass::TreeFile { .. } => ArtifactClass::TreeFileArtifact,
                DerivedClass::ArchivedTree { .. } => ArtifactClass::ArchivedTreeArtifact,
            },
        }
    }

    /// Java `instanceof DerivedArtifact`.
    pub fn is_derived_artifact_instance(&self) -> bool {
        matches!(self.0.kind, ArtifactKind::Derived(_))
    }

    /// Java `instanceof SpecialArtifact`.
    pub fn is_special_artifact_instance(&self) -> bool {
        self.artifact_class() == ArtifactClass::SpecialArtifact
    }

    /// `SpecialArtifact.getSpecialArtifactType()`; `None` for other classes.
    // Java: com/google/devtools/build/lib/actions/Artifact.java:898 SpecialArtifact.getSpecialArtifactType
    pub fn get_special_artifact_type(&self) -> Option<SpecialArtifactType> {
        match &self.0.kind {
            ArtifactKind::Derived(DerivedData {
                class: DerivedClass::Special(t),
                ..
            }) => Some(*t),
            _ => None,
        }
    }

    fn derived(&self) -> Option<&DerivedData> {
        match &self.0.kind {
            ArtifactKind::Derived(d) => Some(d),
            ArtifactKind::Source { .. } => None,
        }
    }

    fn expect_derived(&self) -> &DerivedData {
        self.derived()
            .unwrap_or_else(|| panic!("ClassCastException: {} is not a DerivedArtifact", self))
    }

    /// Reference identity (Java `==`).
    pub fn ptr_eq(a: &Artifact, b: &Artifact) -> bool {
        Arc::ptr_eq(&a.0, &b.0)
    }

