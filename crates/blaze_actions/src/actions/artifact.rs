    // Java: com/google/devtools/build/lib/actions/Artifact.java:1122 TreeFileArtifact.<init>
    fn new_tree_file(
        parent: &Artifact,
        parent_relative_path: PathFragment,
        owner_key: ActionLookupKeyRef,
        generating_action_key: Option<ActionLookupData>,
    ) -> Artifact {
        let exec_path = parent.get_exec_path().get_relative(&parent_relative_path);
        let artifact = Artifact::new_derived(
            parent.get_root().clone(),
            exec_path,
            owner_key,
            generating_action_key,
            DerivedClass::TreeFile {
                parent: parent.clone(),
                parent_relative_path: parent_relative_path.clone(),
            },
        );
        check_argument!(
            parent.is_tree_artifact(),
            "The parent of TreeFileArtifact (parent-relative path: {}) is not a TreeArtifact: {}",
            parent_relative_path,
            parent
        );
        check_argument!(
            !parent_relative_path.contains_uplevel_references()
                && !parent_relative_path.is_absolute(),
            "{} is not a proper normalized relative path",
            parent_relative_path
        );
        artifact
    }

    /// Creates an archived tree artifact with a given `root` and `exec_path` (the default derived
    /// tree root `:archived_tree_artifacts`).
    // Java: com/google/devtools/build/lib/actions/Artifact.java:966 ArchivedTreeArtifact.createForTree
    pub fn create_archived_tree_artifact_for_tree(tree_artifact: &Artifact) -> Artifact {
        let file_name = format!("{}.zip", tree_artifact.get_filename());
        Artifact::create_archived_with_custom_derived_tree_root(
            tree_artifact,
            &PathFragment::create(DEFAULT_DERIVED_TREE_ROOT),
            &tree_artifact
                .get_root_relative_path()
                .replace_name(&file_name)
                .expect("replaceName"),
        )
    }

    /// Creates an `ArchivedTreeArtifact` for a given tree artifact at the path inside a custom
    /// derived tree root.
    // Java: com/google/devtools/build/lib/actions/Artifact.java:985 ArchivedTreeArtifact.createWithCustomDerivedTreeRoot
    pub fn create_archived_with_custom_derived_tree_root(
        tree_artifact: &Artifact,
        derived_tree_root: &PathFragment,
        root_relative_path: &PathFragment,
    ) -> Artifact {
        let tree_root = tree_artifact.get_root();
        let archive_root = embed_derived_tree_root(tree_root.get_exec_path(), derived_tree_root);
        let root = ArtifactRoot::as_derived_root_fragment(
            &get_exec_root(tree_root),
            RootType::OUTPUT,
            archive_root.clone(),
        );
        let generating_action_key = tree_artifact.get_generating_action_key().clone();
        let artifact = Artifact::new_derived(
            root,
            archive_root.get_relative(root_relative_path),
            generating_action_key.get_action_lookup_key().clone(),
            Some(generating_action_key),
            DerivedClass::ArchivedTree {
                tree_artifact: tree_artifact.clone(),
            },
        );
        // Java: com/google/devtools/build/lib/actions/Artifact.java:939 ArchivedTreeArtifact.<init>
        check_argument!(
            tree_artifact.is_tree_artifact(),
            "Not a tree artifact: {}",
            tree_artifact
        );
        artifact
    }

    /// Returns an exec path within the archived artifacts directory tree corresponding to the
