/// An Artifact represents a file used by the build system, whether it's a source file or a
/// derived (output) file. Not all Artifacts have a corresponding FileTarget object in the
/// `build.lib.packages` API: for example, low-level intermediaries internal to a given rule, such
/// as a Java class files or C++ object files. However all FileTargets have a corresponding
/// Artifact.
///
/// In any given call to `SkyframeExecutor#buildArtifacts()`, no two Artifacts in the action graph
/// may refer to the same path.
///
/// Artifacts generated by an action are derived artifacts: their root is a derived root, and they
/// have a generating action. Artifacts whose root is a source root are source artifacts.
// Java: com/google/devtools/build/lib/actions/Artifact.java:119 Artifact
#[derive(Clone)]
pub struct Artifact(Arc<ArtifactInner>);

struct ArtifactInner {
    root: ArtifactRoot,
    exec_path: PathFragment,
    kind: ArtifactKind,
}

enum ArtifactKind {
    // Java: com/google/devtools/build/lib/actions/Artifact.java:754 Artifact.SourceArtifact
    Source { owner: ArtifactOwner },
    // Java: com/google/devtools/build/lib/actions/Artifact.java:218 Artifact.DerivedArtifact
    Derived(DerivedData),
}

/// The owner of a derived artifact: Java's `Object owner` field, first an `ActionLookupKey`,
/// then (after `setGeneratingActionKey`) an `ActionLookupData`.
struct DerivedData {
    owner_key: ActionLookupKeyRef,
    generating_action_key: OnceLock<ActionLookupData>,
    class: DerivedClass,
}

/// The concrete Java class of a derived artifact.
enum DerivedClass {
    Derived,
    // Java: com/google/devtools/build/lib/actions/Artifact.java:840 Artifact.SpecialArtifact
    Special(SpecialArtifactType),
    // Java: com/google/devtools/build/lib/actions/Artifact.java:1056 Artifact.TreeFileArtifact
    TreeFile {
        parent: Artifact,
        parent_relative_path: PathFragment,
    },
    // Java: com/google/devtools/build/lib/actions/Artifact.java:933 Artifact.ArchivedTreeArtifact
    ArchivedTree {
        tree_artifact: Artifact,
    },
}

/// Java class identity, used by `equals` (distinct classes of Artifact are never equal).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ArtifactClass {
    SourceArtifact,
    DerivedArtifact,
    SpecialArtifact,
    TreeFileArtifact,
    ArchivedTreeArtifact,
}

