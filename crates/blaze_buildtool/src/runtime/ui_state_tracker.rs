    fn sample_oldest_actions(
        &self,
        st: &State,
        terminal_writer: &mut dyn AnsiTerminalWriter,
    ) -> io::Result<()> {
        // Running actions first, then by start time; Java breaks the remaining ties by the
        // ActionState's identity hash code (unspecified), the port by insertion order.
        let mut priority_heap: Vec<(Artifact, Arc<ActionState>)> = st
            .active_actions
            .iter()
            .map(|(k, v)| (k.clone(), v.clone()))
            .collect();
        priority_heap.sort_by(|(_, a), (_, b)| {
            let a_running = a.get_phase() == ActionPhase::Running;
            let b_running = b.get_phase() == ActionPhase::Running;
            b_running
                .cmp(&a_running)
                .then(a.nano_start_time().cmp(&b.nano_start_time()))
        });
        let actual_observed_active_actions_count = priority_heap.len() as i32;

        let mut count = 0;
        let mut total_count = 0;
        let nano_time = self.clock.nano_time();
        let mut to_skip: HashSet<Artifact> = HashSet::new();

        for (key, value) in priority_heap {
            total_count += 1;
            if to_skip.contains(&key) {
                continue;
            }
            count += 1;
            if count > st.sample_size {
                total_count -= 1;
                break;
            }
            let width = st.target_width
                - 4
                - if count >= st.sample_size && count < actual_observed_active_actions_count {
                    char_len(AND_MORE)
                } else {
                    0
                };
            let description =
                Self::describe_action(st, &value, nano_time, width, Some(&mut to_skip));
            terminal_writer
                .newline()?
                .append(&format!("    {description}"))?;
        }
        if total_count < actual_observed_active_actions_count {
            terminal_writer.append(AND_MORE)?;
        }
        Ok(())
    }

