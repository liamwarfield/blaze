/// Tracker of strategy names to unique IDs and viceversa.
///
/// The IDs generated by this class can be used to index bitmaps.
// Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:124 UiStateTracker.StrategyIds
pub struct StrategyIds {
    /// Counter of unique strategies seen so far.
    counter: AtomicI32,
    /// Mapping of strategy names to their unique IDs, and of IDs to their names.
    maps: Mutex<(IndexMap<String, i32>, IndexMap<i32, String>)>,
    fallback_id: i32,
}

impl StrategyIds {
    /// Fallback name in case we exhaust our space for IDs.
    // Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:126 StrategyIds.FALLBACK_NAME
    pub const FALLBACK_NAME: &'static str = "unknown";

    /// Constructs a new collection of strategy IDs.
    // Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:140 StrategyIds.<init>
    pub fn new() -> StrategyIds {
        let mut ids = StrategyIds {
            counter: AtomicI32::new(0),
            maps: Mutex::new((IndexMap::new(), IndexMap::new())),
            fallback_id: 0,
        };
        // fallbackId = getId(FALLBACK_NAME); getId reads fallbackId (still null in Java) only
        // once 32 ids are taken.
        ids.fallback_id = ids.get_id(Self::FALLBACK_NAME);
        ids
    }

    /// Computes the ID of a strategy given its name.
    // Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:144 StrategyIds.getId
    pub fn get_id(&self, strategy: &str) -> i32 {
        let mut maps = self.maps.lock();
        let id = match maps.0.get(strategy) {
            Some(id) => *id,
            None => {
                let value = self.counter.fetch_add(1, Ordering::SeqCst);
                let id = if value >= i32::BITS as i32 {
                    self.fallback_id
                } else {
                    1i32.wrapping_shl(value as u32)
                };
                maps.0.insert(strategy.to_owned(), id);
                id
            }
        };
        maps.1.entry(id).or_insert_with(|| strategy.to_owned());
        id
    }

    /// `fallbackId`.
    pub fn fallback_id(&self) -> i32 {
        self.fallback_id
    }

    /// Flattens a bitmap of strategy IDs into a human-friendly string.
    // Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:161 StrategyIds.formatNames
    pub fn format_names(&self, bitmap: i32) -> String {
        let maps = self.maps.lock();
        let mut bitmap = bitmap;
        let mut builder = String::new();
        let mut mask: i32 = 0x1;
        while bitmap != 0 {
            let id = bitmap & mask;
            if id != 0 {
                let name = maps
                    .1
                    .get(&id)
                    .unwrap_or_else(|| panic!("Unknown strategy with id {id}"));
                builder.push_str(name);
                bitmap &= !mask;
                if bitmap != 0 {
                    builder.push_str(", ");
                }
            }
            mask = mask.wrapping_shl(1);
        }
        builder
    }
}

