    // Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:1103 UiStateTracker.shortenUrl
    fn shorten_url(url: &str, width: i32) -> String {
        if char_len(url) < width {
            return url.to_owned();
        }

        // Try to shorten to the form prot://host/.../rest/path/filename
        if let Some(protocol_index) = url.find(URL_PROTOCOL_SEP)
            && protocol_index > 0
        {
            let split = protocol_index + URL_PROTOCOL_SEP.len() + 1;
            if split <= url.len() && url.is_char_boundary(split) {
                let mut prefix = url[..split].to_owned();
                let rest = &url[split..];
                if let Some(host_index) = rest.find('/')
                    && host_index > 0
                {
                    prefix.push_str(&rest[..=host_index]);
                    let rest = &rest[host_index + 1..];
                    let target_length = width - char_len(&prefix);
                    // accept this form of shortening, if what is left from the filename is
                    // significantly longer (twice as long) as the ellipsis symbol introduced
                    if target_length > 3 * char_len(ELLIPSIS) {
                        let short_path = Self::suffix(rest, target_length - char_len(ELLIPSIS));
                        return match short_path.find('/') {
                            Some(slash_pos) => {
                                format!("{prefix}{ELLIPSIS}{}", &short_path[slash_pos..])
                            }
                            None => format!("{prefix}{ELLIPSIS}{short_path}"),
                        };
                    }
                }
            }
        }

        // Last resort: just take a suffix
        if width <= char_len(ELLIPSIS) {
            // No chance to shorten anyway
            return String::new();
        }
        format!(
            "{ELLIPSIS}{}",
            Self::suffix(url, width - char_len(ELLIPSIS))
        )
    }

    // Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:1140 UiStateTracker.reportOnOneDownload
    fn report_on_one_download(
        url: &str,
        download_data: &DownloadData,
        current_nano_time: i64,
        width: i32,
        terminal_writer: &mut dyn AnsiTerminalWriter,
    ) -> io::Result<()> {
        let mut postfix = String::new();

        let nano_download_time = current_nano_time - download_data.nano_start_time;
        let download_seconds = nano_download_time / NANOS_PER_SECOND;

        let progress = &download_data.latest_progress;
        if !progress.is_empty() {
            postfix = format!("{postfix} {progress}");
        }
        if download_seconds > SHOW_TIME_THRESHOLD_SECONDS {
            postfix = format!("{postfix} {download_seconds}s");
        }
        if !postfix.is_empty() {
            postfix = format!(";{postfix}");
        }
        let url = Self::shorten_url(
            url,
            (width - char_len(&postfix)).max(3 * char_len(ELLIPSIS)),
        );
        terminal_writer.append(&format!("{url}{postfix}"))?;
        Ok(())
    }

    // Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:1167 UiStateTracker.reportOnDownloads
    fn report_on_downloads(
        &self,
        st: &State,
        terminal_writer: &mut PositionAwareAnsiTerminalWriter<'_>,
    ) -> io::Result<()> {
        let mut running_downloads_snapshot: Vec<(String, DownloadData)> = st
            .running_downloads
            .iter()
            .map(|(k, v)| (k.clone(), v.clone()))
            .collect();
        running_downloads_snapshot.sort_by_key(|(_, d)| d.nano_start_time);
        let mut count = 0;
        let nano_time = self.clock.nano_time();
        let download_count = running_downloads_snapshot.len() as i32;
        let suffix = format!("{AND_MORE} ({download_count} fetches)");
        for (url, data) in &running_downloads_snapshot {
            if count >= st.sample_size {
                break;
            }
            count += 1;
            if terminal_writer.get_position() != 0 {
                terminal_writer.newline()?;
            }
            terminal_writer.append(FETCH_PREFIX)?;
            Self::report_on_one_download(
                url,
                data,
                nano_time,
                st.target_width
                    - char_len(FETCH_PREFIX)
                    - if count >= st.sample_size && count < download_count {
                        char_len(&suffix)
                    } else {
                        0
                    },
                terminal_writer,
            )?;
        }
        if count < download_count {
            terminal_writer.append(&suffix)?;
        }
        Ok(())
    }

    /// Display any action uploads/downloads that are still active after the build. Most likely,
    /// because upload/download takes longer than the build itself.
    // Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:1203 UiStateTracker.maybeReportActiveUploadsOrDownloads
    fn maybe_report_active_uploads_or_downloads(
        &self,
        st: &State,
        terminal_writer: &mut PositionAwareAnsiTerminalWriter<'_>,
    ) -> io::Result<()> {
        let uploads = st.active_action_uploads;
        let downloads = st.active_action_downloads;

        if !self.build_completed(st) || (uploads == 0 && downloads == 0) {
            return Ok(());
        }

        let wait_millis = self.clock.current_time_millis() - st.build_complete_at;
        let wait_seconds = wait_millis.div_euclid(1000);
        if wait_seconds == 0 {
            // Special case for when bazel was interrupted, in which case we don't want to have a
            // message.
            return Ok(());
        }

        let mut suffix = String::new();
        if wait_millis > SHOW_TIME_THRESHOLD_SECONDS * 1000 {
            suffix = format!("; {wait_seconds}s");
        }

        let mut message = String::from("Waiting for remote cache: ");
        if uploads != 0 {
            if uploads == 1 {
                message.push_str("1 upload");
            } else {
                message.push_str(&format!("{uploads} uploads"));
            }
        }

        if downloads != 0 {
            if uploads != 0 {
                message.push_str(", ");
            }

            if downloads == 1 {
                message.push_str("1 download");
            } else {
                message.push_str(&format!("{downloads} downloads"));
            }
        }

        terminal_writer
            .newline()?
            .append(&message)?
            .append(&suffix)?;
        Ok(())
    }

