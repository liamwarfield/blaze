#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum ActionPhase {
    Preparing,
    Scanning,
    Caching,
    Scheduling,
    Running,
}

impl ActionPhase {
    /// Returns a human-readable description of this phase.
    // Java: com/google/devtools/build/lib/runtime/UiStateTracker.java:207 ActionPhase.describe
    fn describe(self) -> &'static str {
        match self {
            ActionPhase::Preparing => "Preparing",
            ActionPhase::Scanning => "Scanning",
            ActionPhase::Caching => "Caching",
            ActionPhase::Scheduling => "Scheduling",
            ActionPhase::Running => "Running",
        }
    }
}

