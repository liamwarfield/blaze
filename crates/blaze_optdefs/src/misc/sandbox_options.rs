// Java: com/google/devtools/build/lib/sandbox/SandboxOptions.java:50 SandboxOptions.MountPairConverter
/// A converter for customized path mounting pair from the parameter list of a bazel command
/// invocation. Pairs are expected to have the form 'source:target'.
#[derive(Clone, Copy, Debug, Default)]
pub struct MountPairConverter;

impl Converter for MountPairConverter {
    // Java: com/google/devtools/build/lib/sandbox/SandboxOptions.java:54 SandboxOptions.MountPairConverter.convert
    fn convert(
        &self,
        input: Option<&str>,
        _: Option<&ConversionContext>,
    ) -> Result<Option<Value>, OptionsParsingException> {
        let input = non_null(input);
        let mut paths: Vec<String> = Vec::new();
        for path in split_on_unescaped_colon(input) {
            // Split on ':' but not on '\:'
            if !path.trim_matches(|c: char| c <= ' ').is_empty() {
                paths.push(path.replace("\\:", ":"));
            } else {
                return Err(OptionsParsingException::new(format!(
                    "Input {} contains one or more empty paths. Input must be a single path to \
                     mount inside the sandbox or a mounting pair in the form of 'source:target'",
                    input
                )));
            }
        }

        if paths.is_empty() || paths.len() > 2 {
            return Err(OptionsParsingException::new(
                "Input must be a single path to mount inside the sandbox or a mounting pair in \
                 the form of 'source:target'",
            ));
        }

        Ok(Some(Value::new(if paths.len() == 1 {
            (paths[0].clone(), paths[0].clone())
        } else {
            (paths[0].clone(), paths[1].clone())
        })))
    }

    // Java: com/google/devtools/build/lib/sandbox/SandboxOptions.java:82 SandboxOptions.MountPairConverter.getTypeDescription
    fn get_type_description(&self) -> String {
        "a single path or a 'source:target' pair".into()
    }
}

/// Java `input.split("(?<!\\\\):")`: splits on ':' not preceded by a backslash, and (as
/// `String.split` does) drops trailing empty strings.
fn split_on_unescaped_colon(input: &str) -> Vec<&str> {
    let b = input.as_bytes();
    let mut parts = Vec::new();
    let mut start = 0;
    for i in 0..b.len() {
        if b[i] == b':' && (i == 0 || b[i - 1] != b'\\') {
            parts.push(&input[start..i]);
            start = i + 1;
        }
    }
    parts.push(&input[start..]);
    // An input with no match yields the input itself, even when empty.
    if parts.len() > 1 {
        while parts.last().is_some_and(|p| p.is_empty()) {
            parts.pop();
        }
    }
    parts
}

