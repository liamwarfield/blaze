impl SandboxOptions {
    // Java: com/google/devtools/build/lib/sandbox/SandboxOptions.java:213 SandboxOptions.getInaccessiblePaths
    pub fn get_inaccessible_paths(&self, fs: &FileSystemRef) -> Vec<Path> {
        let mut inaccessible_paths: Vec<Path> = Vec::new();
        for path in &self.sandbox_block_path {
            let blocked_path = fs.get_path(path);
            match blocked_path.resolve_symbolic_links() {
                Ok(p) => inaccessible_paths.push(p),
                // It's OK to block access to an invalid symlink. In this case we'll just make the
                // symlink itself inaccessible, instead of the target, though.
                Err(_) => inaccessible_paths.push(blocked_path),
            }
        }
        // ImmutableSet.copyOf: first occurrence wins, insertion order.
        let mut result: Vec<Path> = Vec::new();
        for p in inaccessible_paths {
            if !result.contains(&p) {
                result.push(p);
            }
        }
        result
    }

    // Java: com/google/devtools/build/lib/sandbox/SandboxOptions.java:371 SandboxOptions.getLimits
    /// `ImmutableMap<String, Double>` built with `buildKeepingLast`: insertion order of first
    /// occurrence, value of last occurrence.
    pub fn get_limits(&self) -> Vec<(String, f64)> {
        let mut map: Vec<(String, f64)> = vec![("memory".to_string(), self.memory_limit_mb as f64)];
        for (k, v) in &self.limits {
            match map.iter_mut().find(|(mk, _)| mk == k) {
                Some(e) => e.1 = *v,
                None => map.push((k.clone(), *v)),
            }
        }
        map
    }
}

