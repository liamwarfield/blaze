option_enum! {
    /// Possible subcommands that can be specified for the `mod` command.
    pub enum ModSubcommand {
        DEPS = "deps",
        GRAPH = "graph",
        ALL_PATHS = "all_paths",
        PATH = "path",
        EXPLAIN = "explain",
        SHOW_REPO = "show_repo",
        SHOW_EXTENSION = "show_extension",
        DUMP_REPO_MAPPING = "dump_repo_mapping",
        TIDY = "tidy",
    }
}

impl ModSubcommand {
    // Java: com/google/devtools/build/lib/bazel/bzlmod/modcommand/ModOptions.java:224 ModOptions.ModSubcommand.isGraph
    /// Whether this subcommand produces a graph output.
    pub fn is_graph(&self) -> bool {
        match self {
            ModSubcommand::DEPS
            | ModSubcommand::GRAPH
            | ModSubcommand::ALL_PATHS
            | ModSubcommand::PATH
            | ModSubcommand::EXPLAIN => true,
            ModSubcommand::SHOW_REPO
            | ModSubcommand::SHOW_EXTENSION
            | ModSubcommand::DUMP_REPO_MAPPING
            | ModSubcommand::TIDY => false,
        }
    }

    // Java: com/google/devtools/build/lib/bazel/bzlmod/modcommand/ModOptions.java:228 ModOptions.ModSubcommand.printValues
    pub fn print_values() -> String {
        use blaze_options::OptionScalar;
        use blaze_options::converters::JavaEnum;
        let values: Vec<String> = ModSubcommand::values()
            .iter()
            .map(|v| v.java_to_string())
            .collect();
        format!("({})", values.join(", "))
    }
}

