impl ModOptions {
    // Java: com/google/devtools/build/lib/bazel/bzlmod/modcommand/ModOptions.java:294 ModOptions.getDefaultOptions
    /// Returns a `ModOptions` filled with default values for testing.
    ///
    /// PORT: Java starts from `new ModOptions()`, whose unset reference fields are `null`; here the
    /// unset non-nullable fields (`base_module`, `extension_usages`) hold the macro's raw
    /// placeholders instead.
    pub fn get_default_options() -> ModOptions {
        let mut options = ModOptions::__new_raw();
        options.depth = i32::MAX;
        options.cycles = false;
        options.include_unused = false;
        options.verbose = false;
        options.modules_from = vec![ModuleArg::SpecificVersionOfModule(ModuleKey::root())];
        options.charset = Charset::UTF8;
        options.output_format = OutputFormat::TEXT;
        options.extension_filter = None;
        options.extension_info = ExtensionShow::HIDDEN;
        options
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::misc::test_support::{check_options_class, parse};

    #[test]
    fn options_class_matches_java() {
        check_options_class::<ModOptions>(&[
            "from",
            "verbose",
            "include_unused",
            "extension_filter",
            "extension_info",
            "base_module",
            "extension_usages",
            "depth",
            "cycles",
            "include_builtin",
            "charset",
            "output",
            "all_repos",
            "all_visible_repos",
        ]);
    }

    #[test]
    fn parses_flags() {
        let o = parse::<ModOptions>(&[
            "--from=foo@1.0,@bar",
            "--extension_filter=@rules_java//java:extensions.bzl%toolchains",
            "--base_module=@@baz+",
            "--output=json",
            "--charset=ascii",
            "--extension_info=all",
        ])
        .unwrap();
        assert_eq!(
            o.modules_from
                .iter()
                .map(blaze_options::OptionScalar::java_to_string)
                .collect::<Vec<_>>(),
            vec!["foo@1.0", "@bar"]
        );
        assert_eq!(o.extension_filter.as_ref().unwrap().len(), 1);
        assert_eq!(
            blaze_options::OptionScalar::java_to_string(&o.base_module),
            "@@baz+"
        );
        assert_eq!(o.output_format, OutputFormat::JSON);
        assert_eq!(o.charset, Charset::ASCII);
        assert_eq!(o.extension_info, ExtensionShow::ALL);

        let d = ModOptions::default();
        assert_eq!(
            d.modules_from,
            vec![ModuleArg::SpecificVersionOfModule(ModuleKey::root())]
        );
        assert!(d.extension_usages.is_empty());
        assert_eq!(d.depth, -1);
    }

    #[test]
    fn mod_subcommand() {
        assert_eq!(
            ModSubcommand::print_values(),
            "(deps, graph, all_paths, path, explain, show_repo, show_extension, \
             dump_repo_mapping, tidy)"
        );
        assert!(ModSubcommand::EXPLAIN.is_graph());
        assert!(!ModSubcommand::TIDY.is_graph());
        assert_eq!(ModOptions::get_default_options().depth, i32::MAX);
    }
}
