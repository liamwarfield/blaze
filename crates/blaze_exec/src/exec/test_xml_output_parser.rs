//! Port of `exec/TestXmlOutputParser.java` and `exec/TestXmlOutputParserException.java`.
//!
//! PORT: Java reads the stream with the JDK's StAX `XMLStreamReader`; this port pulls events from
//! `quick_xml` with the same structure (empty elements expanded to a start and an end event, as
//! StAX reports them; end tag names checked). Element and attribute names are local names (the
//! default `XMLInputFactory` is namespace aware). The strings stored in the `TestCase` are the
//! decoded Unicode text, as the Java `String`s StAX returns.

use std::io::Read;

use blaze_protos::blaze::TestCase;
use blaze_protos::blaze::test_case::{Status, Type};
use quick_xml::Reader;
use quick_xml::events::{BytesStart, Event};

/// An exception thrown when the test.xml cannot be parsed.
// Java: com/google/devtools/build/lib/exec/TestXmlOutputParserException.java:19 TestXmlOutputParserException
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{message}")]
pub struct TestXmlOutputParserException {
    pub message: String,
}

impl TestXmlOutputParserException {
    fn new(message: impl Into<String>) -> TestXmlOutputParserException {
        TestXmlOutputParserException {
            message: message.into(),
        }
    }
}

/// jUnit can use either "testsuites" or "testsuite".
// Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:33 TestXmlOutputParser.TOPLEVEL_ELEMENT_NAMES
const TOPLEVEL_ELEMENT_NAMES: [&str; 2] = ["testsuites", "testsuite"];

/// The events of `XMLStreamReader.next()` this parser distinguishes.
enum XmlEvent {
    StartElement(StartElement),
    EndElement(String),
    EndDocument,
    Other,
}

/// A `START_ELEMENT`: its local name and its attributes (local name, value), in order.
struct StartElement {
    local_name: String,
    attributes: Vec<(String, String)>,
}

/// The parse failures Java distinguishes: `XMLStreamException` and `NumberFormatException` (both
/// become a `TestXmlOutputParserException`), and the parser's own exception.
enum ParseError {
    Xml(String),
    NumberFormat,
    Parser(TestXmlOutputParserException),
}

/// `XMLStreamReader` over the whole document.
struct XmlStreamReader<'a> {
    input: &'a [u8],
    reader: Reader<&'a [u8]>,
    buf: Vec<u8>,
}

impl<'a> XmlStreamReader<'a> {
    fn new(input: &'a [u8]) -> XmlStreamReader<'a> {
        let mut reader = Reader::from_reader(input);
        let config = reader.config_mut();
        config.expand_empty_elements = true;
        config.check_end_names = true;
        XmlStreamReader {
            input,
            reader,
            buf: Vec::new(),
        }
    }

    /// `XMLStreamReader.next()`.
    fn next(&mut self) -> Result<XmlEvent, ParseError> {
        self.buf.clear();
        let event = self
            .reader
            .read_event_into(&mut self.buf)
            .map_err(|e| ParseError::Xml(e.to_string()))?;
        Ok(match event {
            Event::Start(start) => XmlEvent::StartElement(start_element(&start)?),
            Event::End(end) => XmlEvent::EndElement(utf8(end.local_name().as_ref())?.to_owned()),
            Event::Eof => XmlEvent::EndDocument,
            Event::Empty(_) => unreachable!("expand_empty_elements"),
            _ => XmlEvent::Other,
        })
    }

    /// `parser.getLocation().getLineNumber() + ":" + getColumnNumber()`.
    fn location(&self) -> String {
        let position = (self.reader.buffer_position() as usize).min(self.input.len());
        let consumed = &self.input[..position];
        let line = consumed.iter().filter(|b| **b == b'\n').count() + 1;
        let line_start = consumed
            .iter()
            .rposition(|b| *b == b'\n')
            .map_or(0, |i| i + 1);
        let column = position - line_start + 1;
        format!("{line}:{column}")
    }
}

fn utf8(bytes: &[u8]) -> Result<&str, ParseError> {
    std::str::from_utf8(bytes).map_err(|e| ParseError::Xml(e.to_string()))
}

fn start_element(start: &BytesStart<'_>) -> Result<StartElement, ParseError> {
    let local_name = utf8(start.local_name().as_ref())?.to_owned();
    let mut attributes = Vec::new();
    for attribute in start.attributes() {
        let attribute = attribute.map_err(|e| ParseError::Xml(e.to_string()))?;
        let name = utf8(attribute.key.local_name().as_ref())?.to_owned();
        let value = attribute
            .unescape_value()
            .map_err(|e| ParseError::Xml(e.to_string()))?
            .into_owned();
        attributes.push((name, value));
    }
    Ok(StartElement {
        local_name,
        attributes,
    })
}

/// Parses a test.xml generated by jUnit or any testing framework into a protocol buffer. The
/// schema of the test.xml is a bit hazy, so there is some guesswork involved.
// Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:31 TestXmlOutputParser
#[derive(Debug, Default)]
pub struct TestXmlOutputParser;

impl TestXmlOutputParser {
    pub fn new() -> TestXmlOutputParser {
        TestXmlOutputParser
    }

    /// PORT: `IOException`s of the stream are returned as `Err(Ok(e))`, the parser's exception
    /// as `Err(Err(e))`; `TestStrategy.parseTestResult` drops both.
    // Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:36 TestXmlOutputParser.parseXmlIntoTestResult
    pub fn parse_xml_into_test_result(
        &self,
        xml_stream: &mut dyn Read,
    ) -> Result<Option<TestCase>, Result<std::io::Error, TestXmlOutputParserException>> {
        let mut input = Vec::new();
        xml_stream.read_to_end(&mut input).map_err(Ok)?;
        self.parse_xml_to_tree(&input).map_err(Err)
    }

    /// Parses the test result XML file into the corresponding protocol buffer.
    ///
    /// Returns the protocol buffer with the parsed data, or `None` if there was an error while
    /// parsing the file.
    // Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:49 TestXmlOutputParser.parseXmlToTree
    fn parse_xml_to_tree(
        &self,
        xml: &[u8],
    ) -> Result<Option<TestCase>, TestXmlOutputParserException> {
        let mut parser = XmlStreamReader::new(xml);
        let result = (|| -> Result<Option<TestCase>, ParseError> {
            loop {
                let event = parser.next()?;
                match event {
                    XmlEvent::EndDocument => return Ok(None),
                    // First find the topmost node.
                    XmlEvent::StartElement(start) => {
                        if TOPLEVEL_ELEMENT_NAMES.contains(&start.local_name.as_str()) {
                            let element_name = start.local_name.clone();
                            let result =
                                self.parse_test_suite(&mut parser, &start, &element_name)?;
                            return Ok(Some(result));
                        }
                    }
                    _ => {}
                }
            }
        })();
        match result {
            Ok(r) => Ok(r),
            Err(ParseError::Xml(message)) => Err(TestXmlOutputParserException::new(message)),
            // The parser is definitely != null here.
            Err(ParseError::NumberFormat) => Err(TestXmlOutputParserException::new(format!(
                "Number could not be parsed at {}",
                parser.location()
            ))),
            Err(ParseError::Parser(e)) => Err(e),
        }
    }

    /// Creates an exception suitable to be thrown when and a bad end tag appears.
    // Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:116 TestXmlOutputParser.createBadElementException
    fn create_bad_element_exception(
        &self,
        expected: &str,
        local_name: &str,
        parser: &XmlStreamReader<'_>,
    ) -> TestXmlOutputParserException {
        TestXmlOutputParserException::new(format!(
            "Expected end of XML element '{}' , but got '{}' at {}",
            expected,
            local_name,
            parser.location()
        ))
    }

    /// Parses a 'testsuite' element.
    // Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:136 TestXmlOutputParser.parseTestSuite
    fn parse_test_suite(
        &self,
        parser: &mut XmlStreamReader<'_>,
        start: &StartElement,
        element_name: &str,
    ) -> Result<TestCase, ParseError> {
        let mut builder = TestCase::default();
        builder.set_type(Type::TestSuite);
        for (name, value) in &start.attributes {
            if name == "name" {
                builder.name = Some(value.clone());
            } else if name == "time" {
                builder.run_duration_millis = Some(parse_time_to_millis(value)?);
            }
        }

        self.parse_contained_elements(parser, element_name, &mut builder)?;
        Ok(builder)
    }

    /// Parses a 'decorator' element.
    // Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:185 TestXmlOutputParser.parseTestDecorator
    fn parse_test_decorator(
        &self,
        parser: &mut XmlStreamReader<'_>,
        start: &StartElement,
    ) -> Result<TestCase, ParseError> {
        let mut builder = TestCase::default();
        builder.set_type(Type::TestDecorator);
        for (name, value) in &start.attributes {
            builder.name = Some(name.clone());
            if name == "classname" {
                builder.class_name = Some(value.clone());
            } else if name == "time" {
                builder.run_duration_millis = Some(parse_time_to_millis(value)?);
            }
        }

        self.parse_contained_elements(parser, "testdecorator", &mut builder)?;
        Ok(builder)
    }

    /// Parses child elements of the specified tag. Strictly speaking, not every element can be a
    /// child of every other, but the HierarchicalTestResult can handle that, and (in this case)
    /// it does not hurt to be a bit more flexible than necessary.
    // Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:213 TestXmlOutputParser.parseContainedElements
    fn parse_contained_elements(
        &self,
        parser: &mut XmlStreamReader<'_>,
        element_name: &str,
        builder: &mut TestCase,
    ) -> Result<(), ParseError> {
        let mut failures = 0;
        let mut errors = 0;
        let mut skipped = false;

        loop {
            let event = parser.next()?;
            match event {
                XmlEvent::StartElement(child) => {
                    // We are not parsing four elements here: system-out, system-err, failure and
                    // error. They potentially contain useful information, but they can be too big
                    // to fit in the memory. We add failure and error elements to the output
                    // without a message, so that there is a difference between passed and failed
                    // test cases.
                    match child.local_name.as_str() {
                        "testsuite" => {
                            let suite = self.parse_test_suite(parser, &child, "testsuite")?;
                            builder.child.push(suite);
                        }
                        "testcase" => {
                            let test_case = self.parse_test_case(parser, &child)?;
                            builder.child.push(test_case);
                        }
                        "failure" => {
                            failures += 1;
                            skip_complete_element(parser)?;
                        }
                        "error" => {
                            errors += 1;
                            skip_complete_element(parser)?;
                        }
                        "skipped" => {
                            skipped = true;
                            skip_complete_element(parser)?;
                        }
                        "testdecorator" => {
                            let decorator = self.parse_test_decorator(parser, &child)?;
                            builder.child.push(decorator);
                        }
                        // Unknown element encountered. Since the schema of the input file is a
                        // bit hazy, just skip it and go merrily on our way. Ignorance is bliss.
                        _ => skip_complete_element(parser)?,
                    }
                }
                XmlEvent::EndElement(local_name) => {
                    // Propagate errors/failures from children up to the current case
                    for child in &builder.child {
                        if child.status() == Status::Error {
                            errors += 1;
                        }
                        if child.status() == Status::Failed {
                            failures += 1;
                        }
                    }

                    if errors > 0 {
                        builder.set_status(Status::Error);
                    } else if failures > 0 {
                        builder.set_status(Status::Failed);
                    } else if skipped {
                        builder.set_status(Status::Skipped);
                    } else {
                        builder.set_status(Status::Passed);
                    }
                    // This is the end tag of the element we are supposed to parse. Hooray, tell
                    // our superiors that our mission is complete.
                    if local_name != element_name {
                        return Err(ParseError::Parser(self.create_bad_element_exception(
                            element_name,
                            &local_name,
                            parser,
                        )));
                    }
                    return Ok(());
                }
                // PORT: StAX throws at a premature end of the document.
                XmlEvent::EndDocument => {
                    return Err(ParseError::Xml(
                        "XML document structures must start and end within the same entity."
                            .to_owned(),
                    ));
                }
                XmlEvent::Other => {}
            }
        }
    }

    /// Parses a 'testcase' element.
    // Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:288 TestXmlOutputParser.parseTestCase
    fn parse_test_case(
        &self,
        parser: &mut XmlStreamReader<'_>,
        start: &StartElement,
    ) -> Result<TestCase, ParseError> {
        let mut builder = TestCase::default();
        builder.set_type(Type::TestCase);
        for (name, value) in &start.attributes {
            match name.as_str() {
                "name" => builder.name = Some(value.clone()),
                "classname" => builder.class_name = Some(value.clone()),
                "time" => builder.run_duration_millis = Some(parse_time_to_millis(value)?),
                "result" => builder.result = Some(value.clone()),
                "status" => {
                    if value == "notrun" {
                        builder.run = Some(false);
                    } else if value == "run" {
                        builder.run = Some(true);
                    }
                }
                _ => {}
            }
        }

        self.parse_contained_elements(parser, "testcase", &mut builder)?;
        Ok(builder)
    }
}

/// Parses a time value in test.xml xs:decimal format, returned as milliseconds.
// Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:160 TestXmlOutputParser.parseTimeToMillis
fn parse_time_to_millis(string: &str) -> Result<i64, ParseError> {
    // xs:decimal values are supposed to look like "12.34" and represent a number of seconds,
    // however we also support two other formats.
    //   * "12" (no decimal point). For Historical Reasons we assume this is a number of
    //     milliseconds.
    //   * "1e2" or "1.2E3" (scientific e notation). Some JUNIT writers incorrectly don't use
    //     xs:decimal, and we want Bazel to still work with them. See
    //     https://github.com/bazelbuild/bazel/issues/24605.

    if string.contains('.') || string.contains('e') || string.contains('E') {
        // test.xml times are supposed to be in seconds.
        let seconds = java_parse_float(string).ok_or(ParseError::NumberFormat)?;
        Ok(java_math_round_float(seconds * 1000.0) as i64)
    } else {
        java_parse_long(string).ok_or(ParseError::NumberFormat)
    }
}

/// `Float.parseFloat`: surrounding characters `<= ' '` are trimmed, an optional `f`/`F`/`d`/`D`
/// suffix is allowed, and the only words are `NaN` and `Infinity`.
///
/// PORT: hexadecimal floating-point literals (`0x1.8p1`) are not accepted.
fn java_parse_float(s: &str) -> Option<f32> {
    let s = s.trim_matches(|c: char| c <= ' ');
    let body = s.strip_suffix(['f', 'F', 'd', 'D']).unwrap_or(s);
    let unsigned = body.strip_prefix(['+', '-']).unwrap_or(body);
    if unsigned == "NaN" || unsigned == "Infinity" {
        let value = if unsigned == "NaN" {
            f32::NAN
        } else {
            f32::INFINITY
        };
        // Java does not accept a suffix after NaN or Infinity.
        if body.len() != s.len() {
            return None;
        }
        return Some(if body.starts_with('-') { -value } else { value });
    }
    if unsigned.is_empty()
        || !unsigned
            .chars()
            .all(|c| c.is_ascii_digit() || c == '.' || c == 'e' || c == 'E' || c == '+' || c == '-')
    {
        return None;
    }
    body.parse::<f32>().ok()
}

/// `Math.round(float)`: rounds half up, `NaN` is 0, and the result saturates to the `int` range.
fn java_math_round_float(a: f32) -> i32 {
    (a as f64 + 0.5).floor() as i32
}

/// `Long.parseLong` (radix 10).
fn java_parse_long(s: &str) -> Option<i64> {
    let digits = s.strip_prefix(['+', '-']).unwrap_or(s);
    if digits.is_empty() || !digits.chars().all(|c| c.is_ascii_digit()) {
        return None;
    }
    s.parse::<i64>().ok()
}

/// Skips over a complete XML element on the input. Precondition: the cursor is at a
/// START_ELEMENT. Postcondition: the cursor is at an END_ELEMENT.
// Java: com/google/devtools/build/lib/exec/TestXmlOutputParser.java:331 TestXmlOutputParser.skipCompleteElement
fn skip_complete_element(parser: &mut XmlStreamReader<'_>) -> Result<(), ParseError> {
    let mut depth = 1;
    loop {
        let event = parser.next()?;

        match event {
            XmlEvent::StartElement(_) => depth += 1,
            XmlEvent::EndElement(_) => {
                depth -= 1;
                if depth == 0 {
                    return Ok(());
                }
            }
            // PORT: StAX throws at a premature end of the document.
            XmlEvent::EndDocument => {
                return Err(ParseError::Xml(
                    "XML document structures must start and end within the same entity.".to_owned(),
                ));
            }
            XmlEvent::Other => {}
        }
    }
}
