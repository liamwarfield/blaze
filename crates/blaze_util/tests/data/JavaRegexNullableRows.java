// Generates crates/blaze_util/tests/data/java_regex_nullable_rows.rs: Matcher.find() spans and
// matches() of repetitions whose body can match the empty string (review loading-2 F5), from
// java.util.regex.Pattern.
//
// Run (JDK 25, the JDK embedded in Bazel 9.3.2):
//   java crates/blaze_util/tests/data/JavaRegexNullableRows.java \
//     > crates/blaze_util/tests/data/java_regex_nullable_rows.rs
//
// Each row: (pattern, input, find span in code points or None, matches()).
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class JavaRegexNullableRows {
  static String rs(String s) {
    StringBuilder b = new StringBuilder("\"");
    s.codePoints()
        .forEach(
            c -> {
              if (c == '\\') b.append("\\\\");
              else if (c == '"') b.append("\\\"");
              else if (c >= 0x20 && c < 0x7f) b.append((char) c);
              else b.append(String.format("\\u{%x}", c));
            });
    return b.append("\"").toString();
  }

  public static void main(String[] args) {
    String[] bodies = {
      "a*|b", "b|a*", "a?|b", "b|a?", "|a", "a|", "a*", "a*?", "a??", "a?", "(?:a|)", "(?:|a)",
      "\\s*|#.*", "[a-c]*|d", "a*b?", "b?a*", "a*?b", "\\b|a", "a|\\b", "x*|a|b", "a+|", "a*b*",
      "(a*)", "(a*|b)", "a*|b*", "(?:a*|b)c?", "(?:a|b)*", "ab|a*", "a{0,2}|b", "a|b|",
      "^|a", "a|$", "(?i)A*|b", "a*+|b", "(?>a*)|b",
      // Review loading-2 round 2 (R1): an empty alternative before non-empty ones of different
      // lengths, and lazy inner quantifiers.
      "|ab|a", "a|ab|", "|a|ab", "ab||a", "a??b?", "(?:|ab|a)c?",
    };
    String[] quantifiers = {
      "*", "+", "?", "{0,3}", "{2}", "{2,}", "{1,2}", "*?", "+?", "{2,3}?", "{1,2}?", "{2}?",
      "{0,2}?", "{0,3}?", "{2,}?", "??"
    };
    String[] suffixes = {"", "b", "c", "$", "(?:b|c)"};
    String[] inputs = {
      "abab", "aab", "ba", "  # x", "abcdabc", "", "bbb", "xab", "aabc", "abc", "ababc", "abac",
      "bac"
    };
    StringBuilder out = new StringBuilder();
    out.append("// Generated by tests/data/JavaRegexNullableRows.java (JDK 25); do not edit.\n");
    out.append("&[\n");
    for (String body : bodies) {
      for (String q : quantifiers) {
        for (String suffix : suffixes) {
          String p = "(?:" + body + ")" + q + suffix;
          Pattern pat;
          try {
            pat = Pattern.compile(p);
          } catch (Exception e) {
            continue;
          }
          for (String in : inputs) {
            Matcher m = pat.matcher(in);
            String find =
                m.find()
                    ? "Some(("
                        + in.codePointCount(0, m.start())
                        + ", "
                        + in.codePointCount(0, m.end())
                        + "))"
                    : "None";
            out.append("    (")
                .append(rs(p))
                .append(", ")
                .append(rs(in))
                .append(", ")
                .append(find)
                .append(", ")
                .append(pat.matcher(in).matches())
                .append("),\n");
          }
        }
      }
    }
    out.append("]\n");
    System.out.print(out);
  }
}
