fn char_index(s: &str, byte: usize) -> usize {
    s[..byte].chars().count()
}

/// The panic text of a `catch_unwind` result.
fn panic_text(e: Box<dyn std::any::Any + Send>) -> String {
    e.downcast_ref::<String>()
        .cloned()
        .or_else(|| e.downcast_ref::<&str>().map(|s| s.to_string()))
        .unwrap_or_default()
}

/// Patterns whose atomic group or possessive quantifier ends the pattern: translated for
/// `find()`, `unported!` under `matches()` (which needs the end of the input after them).
const LOUD_UNDER_MATCHES: &[&str] = &[
    "a*+",
    "ba++",
    "x(?:a|b)?+",
    "a{1,2}+",
    "(?>a*)",
    "(?>a|ab)",
    "(?:(?>a)|(?>a/b))",
    "(?:(?>^c)|(?>_test$)|(?>a/b))",
    "(?:(?>-/javatests[/:])|(?>-/test/java[/:]))",
];

/// Runs one row: `Ok(Ok((find, matches)))` (`matches` is `None` when it failed loudly),
/// `Ok(Err(syntax error))`, or `Err(panic text)`.
#[allow(clippy::type_complexity)]
fn run(
    pattern: &str,
    flags: i32,
    input: &str,
) -> Result<Result<(Option<(usize, usize)>, Option<bool>), String>, String> {
    let compiled = match catch_unwind(|| Pattern::compile(pattern, flags)) {
        Ok(Ok(compiled)) => compiled,
        Ok(Err(message)) => return Ok(Err(message)),
        Err(e) => return Err(panic_text(e)),
    };
    let find = catch_unwind(AssertUnwindSafe(|| {
        let find = compiled
            .find(input)
            .map(|(s, e)| (char_index(input, s), char_index(input, e)));
        assert_eq!(compiled.is_match(input), find.is_some());
        find
    }))
    .map_err(panic_text)?;
    let matches = match catch_unwind(AssertUnwindSafe(|| compiled.matches(input))) {
        Ok(matches) => Some(matches),
        Err(e) => {
            let text = panic_text(e);
            if !(LOUD_UNDER_MATCHES.contains(&pattern) && text.contains("not ported yet")) {
                return Err(text);
            }
            None
        }
    };
    Ok(Ok((find, matches)))
}

#[test]
fn rows_follow_java_util_regex_pattern() {
    let mut failures = Vec::new();
    for &(pattern, flags, input, ref expected, loud) in ROWS {
        let got = run(pattern, flags, input);
        let ok = match (&got, loud) {
            (Err(panic), true) => panic.contains("not ported yet"),
            (Ok(Ok((find, matches))), false) => match expected {
                Ok((expected_find, expected_matches)) => {
                    find == expected_find
                        && matches.is_none_or(|matches| matches == *expected_matches)
                }
                Err(_) => false,
            },
            (Ok(Err(message)), false) => Err(message.as_str()) == *expected,
            _ => false,
        };
        if !ok {
            failures.push(format!(
                "pattern {pattern:?} flags {flags} input {input:?}: expected {expected:?} (loud: {loud}), got {got:?}"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} rows differ:\n{}",
        failures.len(),
        ROWS.len(),
        failures.join("\n")
    );
}

#[test]
fn translate_and_compile_agree_with_pattern_find() {
    for &(pattern, flags, input, ref expected, loud) in ROWS {
        if loud {
            continue;
        }
        let Ok((find, _)) = expected else {
            assert!(
                java_regex::translate(pattern, flags).is_err(),
                "{pattern:?}"
            );
            continue;
        };
        let regex = java_regex::compile(pattern, flags).unwrap();
        let got = regex
            .find(input)
            .map(|m| (char_index(input, m.start()), char_index(input, m.end())));
        assert_eq!(got, *find, "pattern {pattern:?} input {input:?}");
    }
}

#[test]
fn syntax_error_message_has_javas_layout() {
    // Java: Pattern.compile("a{2") -> PatternSyntaxException.getMessage().
    let message = Pattern::compile("a{2", 0).unwrap_err();
    assert_eq!(message, "Unclosed counted closure near index 3\na{2");
    let message = Pattern::compile("(?<1a>x)", 0).unwrap_err();
    assert_eq!(
        message,
        "capturing group name does not start with a Latin letter near index 3\n(?<1a>x)\n   ^"
    );
}
